#!/usr/bin/env bash
# ============================================================================
# install-hooks.sh — install the global hooks and repair the template layer.
#
# Radar basis: #1 agent sandboxing (Adopt), #17 risk-tiered human oversight,
# #36 agent instruction bloat.
#
# What it does, and it does the same thing every time you run it:
#   1. writes the wrapper scripts for every standard hook name into this
#      directory (each chains to the repo's own .git/hooks/<name> first, so
#      existing per-repo hooks keep working, then runs the pi scanners)
#   2. writes the same wrappers into $HOME/.git-templates/hooks, which `git init`
#      copies into every new repo. That layer was empty and therefore inert.
#   3. sets core.hooksPath and init.templateDir globally
#
# Options:
#   --templates-only   only repair $HOME/.git-templates/hooks + init.templateDir
#   -h, --help         this text
#
# Undo:
#   git config --global --unset core.hooksPath
#   git config --global --unset init.templateDir
#   rm -rf "$HOME/.pi/git-hooks" "$HOME/.git-templates/hooks"
# ============================================================================
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HOOKS_HOME="${PI_GIT_HOOKS_DIR:-$HOME/.pi/git-hooks}"
TEMPLATE_DIR="${GIT_TEMPLATE_DIR:-$HOME/.git-templates}"
TEMPLATES_ONLY=0

for arg in "$@"; do
	case "$arg" in
	--templates-only) TEMPLATES_ONLY=1 ;;
	-h | --help)
		sed -n '2,25p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
		exit 0
		;;
	*)
		printf 'install-hooks: unknown option: %s (try --help)\n' "$arg" >&2
		exit 2
		;;
	esac
done

HOOKS=(
	applypatch-msg pre-applypatch post-applypatch
	pre-commit prepare-commit-msg commit-msg post-commit
	pre-rebase post-checkout post-merge pre-push post-rewrite
	sendemail-validate pre-auto-gc post-index-change
)

write_wrappers() {
	local target=$1 h
	mkdir -p "$target"
	for h in "${HOOKS[@]}"; do
		cat >"$target/$h" <<EOF
#!/usr/bin/env bash
# pi global git hook wrapper — generated by install-hooks.sh, do not edit
set -u
HOOK_NAME="$h"
HOOKS_HOME="\${PI_GIT_HOOKS_DIR:-$HOOKS_HOME}"
GIT_DIR="\$(git rev-parse --git-common-dir 2>/dev/null || echo .git)"
REPO_HOOK="\$GIT_DIR/hooks/\$HOOK_NAME"
if [ -x "\$REPO_HOOK" ] && [ "\$REPO_HOOK" != "\$0" ]; then
	"\$REPO_HOOK" "\$@" || exit \$?
fi
case "\$HOOK_NAME" in
pre-commit)
	# Harness budgets first (milliseconds), then the secret scan, which must
	# still run and still be the thing that decides the commit's fate.
	if [ -x "\$HOOKS_HOME/harness-pre-commit" ]; then
		"\$HOOKS_HOME/harness-pre-commit" "\$@" || exit \$?
	fi
	exec "\$HOOKS_HOME/scan-secrets.sh"
	;;
commit-msg) exec "\$HOOKS_HOME/scan-commitmsg.sh" "\$1" ;;
pre-push) exec "\$HOOKS_HOME/scan-prepush.sh" ;;
esac
exit 0
EOF
		chmod +x "$target/$h"
	done
}

write_wrappers "$TEMPLATE_DIR/hooks"
chmod +x "$DIR"/*.sh 2>/dev/null || true
git config --global init.templateDir "$TEMPLATE_DIR"
printf 'git hooks: template layer repaired -> %s/hooks (%d wrappers)\n' \
	"$TEMPLATE_DIR" "${#HOOKS[@]}"
printf 'git hooks: init.templateDir set to %s\n' "$TEMPLATE_DIR"

if [ "$TEMPLATES_ONLY" = 1 ]; then
	exit 0
fi

write_wrappers "$DIR"
git config --global core.hooksPath "$DIR"
printf 'secret-guard: global core.hooksPath set to %s\n' "$DIR"
printf 'secret-guard: pre-commit (harness budgets + secret scan), commit-msg and pre-push active for all repos\n'
