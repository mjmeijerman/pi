#!/usr/bin/env bash
# Installs global git hooks for secret-guard:
#   1. generates wrapper scripts for all standard hook names in this directory
#      (each chains to the repo's own .git/hooks/<name> so existing hooks keep working)
#   2. sets core.hooksPath globally
# Undo: git config --global --unset core.hooksPath && rm -rf "$HOME/.pi/git-hooks"
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

HOOKS=(
	applypatch-msg pre-applypatch post-applypatch
	pre-commit prepare-commit-msg commit-msg post-commit
	pre-rebase post-checkout post-merge pre-push post-rewrite
	sendemail-validate pre-auto-gc post-index-change
)

for h in "${HOOKS[@]}"; do
	cat > "$DIR/$h" <<EOF
#!/usr/bin/env bash
# secret-guard global hook wrapper (generated by install-hooks.sh)
set -u
HOOK_NAME="$h"
GIT_DIR="\$(git rev-parse --git-common-dir 2>/dev/null || echo .git)"
REPO_HOOK="\$GIT_DIR/hooks/\$HOOK_NAME"
if [ -x "\$REPO_HOOK" ] && [ "\$REPO_HOOK" != "\$0" ]; then
	"\$REPO_HOOK" "\$@" || exit \$?
fi
case "\$HOOK_NAME" in
	pre-commit) exec "\$HOME/.pi/git-hooks/scan-secrets.sh" ;;
	commit-msg) exec "\$HOME/.pi/git-hooks/scan-commitmsg.sh" "\$1" ;;
	pre-push) exec "\$HOME/.pi/git-hooks/scan-prepush.sh" ;;
esac
exit 0
EOF
	chmod +x "$DIR/$h"
done

git config --global core.hooksPath "$DIR"
chmod +x "$DIR"/*.sh 2>/dev/null || true
echo "secret-guard: global core.hooksPath set to $DIR"
echo "secret-guard: pre-commit, commit-msg, and pre-push scans active for all repos"
